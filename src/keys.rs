const ALL_KEYS: &[[u8; 32]] = &[CLOUDFLARE_KEY_A, CLOUDFLARE_KEY_B];

/// Derive the key_id from a public key: it is the last byte of the key.
fn key_id_of(key: &[u8; 32]) -> u32 {
    key[31] as u32
}

/// Look up a Cloudflare public key by key_id (derived from the last byte of each key).
pub(crate) fn get_key(key_id: u32) -> Option<&'static [u8; 32]> {
    ALL_KEYS.iter().find(|k| key_id_of(k) == key_id)
}
